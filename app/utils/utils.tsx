export function initializeCardsArray() {
  const cards = [];
  for (let i = 0; i <= 78; i++) {
    cards.push(i);
  }
  return cards;
}

export function getCardProps(cards: any[]) {
  return cards.map((card) => {
    return {
      name: card.name,
      image: card.image,
    };
  });
}

export const shuffle = (array: any[]) => {
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }
  return array;
};
